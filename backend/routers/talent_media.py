# Admin: toggle
# ---------------------------------------------------------------------------
class MediaDownloadToggleIn(BaseModel):
    enabled: bool


@router.patch("/talents/{tid}/media-download")
async def set_media_download(tid: str, payload: MediaDownloadToggleIn, admin: dict = Depends(current_team_or_admin)):
    """Flip the Media Download Link toggle. The token is minted once (so the
    SAME link survives OFF→ON) and never regenerated here."""
    existing = await db.talents.find_one({"id": tid}, {"_id": 0, "id": 1})
    if not existing:
        raise HTTPException(404, "Talent not found")
    token = await ensure_token(tid)
    await db.talents.update_one({"id": tid}, {"$set": {"media_download_enabled": bool(payload.enabled)}})
    logger.info("talent media link toggled: talent=%s enabled=%s by=%s", tid, payload.enabled, admin.get("email"))
    return {"enabled": bool(payload.enabled), "token": token, "url": media_link_url(token) if token else None}


