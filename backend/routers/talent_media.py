"""Talent Media Download Link.

A private, opaque, LIVE link to one talent's Global Talent media (Indian Look
Images, Western Look Images, Additional Portfolio, Introduction Video), sent
as a second WhatsApp message right after the submission form, plus the public
endpoints that back the client-facing media page.

Design (all reuse — no parallel media system):
  * Media source  : `db.talents[...].media[]` — the SAME array, categories and
                    ordering the Global Talent profile page renders. Nothing is
                    copied or snapshotted; every request reads the talent fresh.
  * Access control: an opaque per-talent token (`media_download_token`, 192-bit,
                    minted once, never regenerated by the toggle) plus an
                    `media_download_enabled` flag. BOTH are checked on EVERY
                    request, so switching the flag OFF kills links already sent
                    and switching it back ON revives the very same link.
                    Missing flag == ON (default); only an explicit False is OFF.
  * Downloads     : individual files stream through the backend (Cloudinary /
                    Stream URLs are resolved server-side and never returned;
                    the browser CSP does not permit direct cross-origin fetch).
                    "Download All" is a CONSTANT-MEMORY streaming ZIP — one file
                    in flight, 64 KiB chunks, STORED (no recompression) — NOT
                    the buffer-everything-in-RAM approach used by the client
                    link ZIP in routers/links.py (deliberately not reused).
  * WhatsApp      : `enqueue_media_link_message` is called by the existing
                    submission-notification task AFTER the form message(s), in
                    its own try/except, and is made idempotent per submission
                    event via `talent_media_link_events` (unique event_key).
"""
import logging
import os
import re
import secrets
import string
