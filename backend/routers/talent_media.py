logger = logging.getLogger("talentgram")

router = APIRouter(prefix="/api", tags=["talent-media"])

MEDIA_LINK_BASE_URL = os.environ.get("TALENT_MEDIA_BASE_URL", "https://links.talentgramagency.com").rstrip("/")

_TOKEN_RE = re.compile(r"^[A-Za-z0-9_-]{20,64}$")
_UNAVAILABLE = "This media link is not available."

# Display order + labels mirror TalentEdit.jsx's media sections exactly.
_SECTIONS: List[Tuple[str, str, str]] = [
    # (response key, stored media category, label)
    ("indian", "indian", "Indian Look Images"),
    ("western", "western", "Western Look Images"),
    ("portfolio", "portfolio", "Additional Portfolio"),
]
_ZIP_FOLDERS = {
    "indian": "Indian Look Images",
    "western": "Western Look Images",
    "portfolio": "Additional Portfolio",
    "video": "Introduction Video",
}
_BLOCKED_STATUSES = {"archived", "merged"}
_IMAGE_EXTS = (".jpg", ".jpeg", ".png", ".webp", ".heic", ".heif", ".gif")

_CHUNK = 64 * 1024
# Concurrent "Download All" streams per process — a hard resource bound.
_ZIP_MAX_CONCURRENT = int(os.environ.get("TALENT_MEDIA_ZIP_MAX_CONCURRENT", "3"))
_zip_slots = asyncio.Semaphore(_ZIP_MAX_CONCURRENT)
_MAX_ZIP_BYTES = 0xFFFFFFFF - (1 << 20)  # stay inside plain (non-zip64) ZIP limits


# ---------------------------------------------------------------------------
# Names / link helpers
# ---------------------------------------------------------------------------
def short_talent_name(name: Optional[str]) -> str:
    """'Angela Kumar' -> 'Angela K'. Everything before the last word is kept
    (multi-word first names stay whole); only the last word is reduced to its
    initial. A single-word name is returned as-is. Never exposes the surname."""
    parts = (name or "").split()
    if not parts:
        return "Talent"
    if len(parts) == 1:
        return parts[0]
    return f"{' '.join(parts[:-1])} {parts[-1][0].upper()}"


def media_link_url(token: str) -> str:
    return f"{MEDIA_LINK_BASE_URL}/talent-media/{token}"


def build_media_link_message(talent_name: Optional[str], token: str) -> str:
    return (
        f"Talentgram X {short_talent_name(talent_name)}\n\n"
        f"Kindly click the link to download pictures and introduction video:\n\n"
        f"{media_link_url(token)}"
    )


def is_media_download_enabled(talent: Optional[dict]) -> bool:
    """Missing flag == ON (default). Only an explicit False disables."""
    return (talent or {}).get("media_download_enabled") is not False


def _safe_filename(s: str) -> str:
    cleaned = "".join(c for c in (s or "") if c.isalnum() or c in " -_.").strip()
    return cleaned or "media"


