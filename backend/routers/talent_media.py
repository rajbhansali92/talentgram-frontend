_indexes_ready = False


async def _ensure_indexes() -> None:
    global _indexes_ready
    if _indexes_ready:
        return
    try:
        await db.talents.create_index(
            "media_download_token", unique=True, name="media_download_token_unique",
            partialFilterExpression={"media_download_token": {"$type": "string"}},
        )
        await db.talent_media_link_events.create_index("event_key", unique=True, name="event_key_unique")
        _indexes_ready = True
    except Exception:
        logger.exception("talent_media index creation failed (non-fatal)")


_TOKEN_ALPHABET = string.ascii_letters + string.digits


def _new_token() -> str:
    """32 chars of [A-Za-z0-9] (~190 bits). Alphanumeric only on purpose: a
    '-' or '_' at the end of a pasted URL is the classic way chat apps
    mis-linkify, and the token is read by machines, not people."""
    return "".join(secrets.choice(_TOKEN_ALPHABET) for _ in range(32))


async def ensure_token(tid: str) -> Optional[str]:
    """Return the talent's media token, minting it exactly once (race-safe:
    the conditional update only ever succeeds for the first writer)."""
    await _ensure_indexes()
    t = await db.talents.find_one({"id": tid}, {"_id": 0, "media_download_token": 1})
    if t is None:
        return None
    if t.get("media_download_token"):
        return t["media_download_token"]
    await db.talents.update_one(
        {"id": tid, "media_download_token": {"$in": [None, ""]}},
        {"$set": {"media_download_token": _new_token()}},
    )
    t = await db.talents.find_one({"id": tid}, {"_id": 0, "media_download_token": 1})
    return (t or {}).get("media_download_token")


async def _talent_for_token(token: str) -> dict:
    """Resolve token -> talent, enforcing the toggle EVERY call. Invalid,
    unknown, disabled and archived/merged all return the same 404 so the
    endpoint reveals nothing about which case applied."""
    if not token or not _TOKEN_RE.match(token):
        raise HTTPException(404, _UNAVAILABLE)
    await _ensure_indexes()
    talent = await db.talents.find_one(
        {"media_download_token": token},
        {"_id": 0, "id": 1, "name": 1, "media": 1, "cover_media_id": 1, "status": 1, "media_download_enabled": 1},
    )
    if (
        not talent
        or not is_media_download_enabled(talent)
        or str(talent.get("status") or "").lower() in _BLOCKED_STATUSES
    ):
        raise HTTPException(404, _UNAVAILABLE)
    return talent


def _rate_limit(request: Request, bucket: str, limit: int, window: float = 60.0) -> None:
    if not rate_limit_ok(f"talent-media:{bucket}:{client_ip(request)}", limit, window):
        raise HTTPException(429, "Too many requests. Please wait a moment and try again.")


# ---------------------------------------------------------------------------
# Canonical media selection (mirrors the Global Talent profile)
# ---------------------------------------------------------------------------
def _visible(m: dict) -> bool:
    # Same "hidden/internal" exclusion the client links apply.
    return bool(m.get("url")) and m.get("client_visible") is not False and m.get("internal_only") is not True


def _ext_for(m: dict, is_video: bool) -> str:
    url = (m.get("url") or "").split("?")[0]
    ext = os.path.splitext(url)[1].lower()
    if is_video:
        return ".mp4" if ext in ("", ".m3u8", ".mpd") else ext
    return ext if ext in _IMAGE_EXTS else ".jpg"


def _collect(talent: dict) -> Dict[str, Any]:
    """{'indian':[media...], 'western':[...], 'portfolio':[...], 'video': media|None}
    in stored (profile) order, from the raw talent document."""
    media = [m for m in (talent.get("media") or []) if _visible(m)]
    out: Dict[str, Any] = {key: [m for m in media if m.get("category") == cat] for key, cat, _ in _SECTIONS}
    videos = [m for m in media if m.get("category") == "video"]
    out["video"] = videos[0] if videos else None  # profile shows videoMedia[0]
    return out


def _item(m: dict, key: str, idx: int, display_name: str, is_video: bool) -> dict:
    pub = _public_media(m)
    label = "introduction-video" if is_video else f"image-{idx:02d}"
    fn = f"{_safe_filename(display_name)} - {_ZIP_FOLDERS[key]} - {label}{_ext_for(m, is_video)}"
    return {
        "id": m.get("id"),
        "kind": "video" if is_video else "image",
        "url": pub.get("url"),
        "poster_url": pub.get("poster_url") or pub.get("thumbnail_url"),
        "duration": pub.get("duration"),
        "content_type": m.get("content_type"),
        "original_filename": m.get("original_filename"),
        "created_at": m.get("created_at"),
        "filename": fn,
    }


def build_media_view(talent: dict) -> dict:
    enriched = enrich_talent({"media": list(talent.get("media") or []), "cover_media_id": talent.get("cover_media_id")})
    shaped = {**talent, "media": enriched["media"]}
    groups = _collect(shaped)
    display = short_talent_name(talent.get("name"))
    sections = []
    total = 0
    for key, _cat, label in _SECTIONS:
        items = [_item(m, key, i, display, False) for i, m in enumerate(groups[key], 1)]
        total += len(items)
        sections.append({"key": key, "label": label, "items": items})
    video = _item(groups["video"], "video", 1, display, True) if groups["video"] else None
    if video:
        total += 1
    return {
        "talent": {"name": display},
        "sections": sections,
        "video": video,
        "total": total,
    }


